package io.github.rikoappdev.composepdf

import java.awt.image.BufferedImage
import java.io.ByteArrayOutputStream
import java.io.File
import java.util.Random
import javax.imageio.ImageIO
import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlin.test.assertTrue

/**
 * Adversarial parity probe for [PdfDocumentSpec.renderTo]. `StreamingRenderTest` covers text + JPEG +
 * PNG + emoji; this covers the object-emission paths it does NOT: `vector()` Form XObjects (SVG and
 * VectorDrawable), `table()` splitting across pages with a repeating header, multi-page pagination
 * with header/footer bands, and `pageNumbers = true`. Also pins the spec-reuse question: rendering the
 * same immutable spec twice must yield the same bytes, whichever transport is used.
 *
 * Synthetic data only — generated shapes, generated noise images, placeholder labels.
 */
class StreamingParityProbeTest {

    private fun regular() = File("src/jvmTest/resources/font/NotoSans-Regular.ttf").readBytes()
    private fun bold() = File("src/jvmTest/resources/font/NotoSans-Bold.ttf").readBytes()

    private fun stream(spec: PdfDocumentSpec, emoji: ByteArray? = null): ByteArray {
        val out = ByteArrayOutputStream()
        spec.renderTo({ b, o, l -> out.write(b, o, l) }, regular(), bold(), emoji)
        return out.toByteArray()
    }

    private fun noisyJpeg(w: Int, h: Int, seed: Long): ByteArray {
        val img = BufferedImage(w, h, BufferedImage.TYPE_INT_RGB)
        val rnd = Random(seed)
        for (y in 0 until h) for (x in 0 until w) img.setRGB(x, y, rnd.nextInt())
        val bos = ByteArrayOutputStream()
        ImageIO.write(img, "jpg", bos)
        return bos.toByteArray()
    }

    private fun pngWithAlpha(w: Int, h: Int): ByteArray {
        val img = BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB)
        for (y in 0 until h) for (x in 0 until w) img.setRGB(x, y, (x * 255 / w shl 24) or 0x3366CC)
        val bos = ByteArrayOutputStream()
        ImageIO.write(img, "png", bos)
        return bos.toByteArray()
    }

    /** Synthetic SVG: a square, a disc and an arc — exercises rect/circle/path + color parsing. */
    private fun svgMark(): ByteArray = """
        <svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 48 48">
          <rect x="2" y="2" width="44" height="44" fill="#2244AA"/>
          <circle cx="24" cy="24" r="14" fill="#FFCC00"/>
          <path d="M 6 40 A 18 18 0 0 1 42 40 L 42 44 L 6 44 Z" fill="#22AA66"/>
        </svg>
    """.trimIndent().encodeToByteArray()

    /** Synthetic Android VectorDrawable: a chevron built from straight segments, even-odd hole. */
    private fun vectorDrawableMark(): ByteArray = """
        <vector xmlns:android="http://schemas.android.com/apk/res/android"
            android:width="32dp" android:height="32dp"
            android:viewportWidth="32" android:viewportHeight="32">
            <path android:pathData="M 2 2 L 30 2 L 30 30 L 2 30 Z M 10 10 L 22 10 L 22 22 L 10 22 Z"
                android:fillColor="#CC3355" android:fillType="evenOdd"/>
        </vector>
    """.trimIndent().encodeToByteArray()

    /**
     * A deliberately many-page document: repeating header/footer bands, auto page numbers, a table
     * long enough to split across pages with its header repeated, both vector flavours, a JPEG and a
     * PNG with alpha. Every object kind the serializer can emit appears at least once.
     */
    private fun kitchenSink(): PdfDocumentSpec = pdfDocument(
        PageConfig(margin = 36.dp, pageNumbers = true, repeatHeader = true)
    ) {
        header {
            row(gap = 8.dp, verticalAlignment = VerticalAlignment.Center) {
                cell(0f) { vector(vectorDrawableMark(), height = 18.dp) }
                cell(1f) { text("Probe Report", TextStyle(fontSize = 13.sp, fontWeight = FontWeight.Bold)) }
            }
            divider()
        }
        footer {
            divider()
            text("Generated by a test fixture", TextStyle(fontSize = 7.sp, align = TextAlign.Center))
        }

        box(padding = 8.dp, border = 1.dp, cornerRadius = 4.dp, background = Color(0xFFF6F8FA)) {
            keyValue("Reference", "PROBE-0001")
            keyValue("Batch", "17")
        }
        spacer(8.dp)
        vector(svgMark(), height = 40.dp, align = HorizontalAlignment.Start)
        spacer(6.dp)
        image(pngWithAlpha(48, 48), height = 20.dp)
        image(noisyJpeg(240, 180, seed = 3L), height = 48.dp)

        table(
            columns = listOf(
                PdfColumn(3f, "Item"),
                PdfColumn(1f, "Qty", TextAlign.End),
                PdfColumn(2f, "Value", TextAlign.End),
            ),
            zebra = Color(0xFFF3F5F7),
            headerBackground = Color(0xFFE6EAEE),
        ) {
            repeat(90) { i ->
                row("Component ${i + 1} with a moderately long descriptive label", "${i % 7 + 1}", "${i * 13 % 997}.00")
            }
            totalRow("Total", "", "12345.00")
        }

        repeat(3) { i ->
            text("Section ${i + 1}", TextStyle(fontSize = 11.sp, fontWeight = FontWeight.Bold))
            text(
                "Paragraph body used to force pagination. ".repeat(24),
                TextStyle(fontSize = 9.sp, align = TextAlign.Start),
            )
            photoGrid(List(3) { noisyJpeg(160, 120, seed = i * 100L + it) }, perRow = 3, cellHeight = 56.dp)
        }
    }

    @Test
    fun kitchenSinkStreamsIdenticalBytes() {
        val expected = kitchenSink().render(regular(), bold())
        val streamed = stream(kitchenSink())
        assertTrue(expected.size > 100_000, "probe doc should be non-trivial, was ${expected.size} B")
        assertContentEquals(expected, streamed, "renderTo must stream byte-identical output")
    }

    /** Vector-only document: the Form XObject path in isolation, no images to mask a mismatch. */
    @Test
    fun vectorOnlyStreamsIdenticalBytes() {
        fun spec() = pdfDocument(PageConfig(margin = 36.dp, pageNumbers = false)) {
            vector(svgMark(), height = 60.dp)
            vector(vectorDrawableMark(), height = 30.dp, align = HorizontalAlignment.End)
        }
        assertContentEquals(spec().render(regular(), bold()), stream(spec()))
    }

    /** Table-only document that must span several pages with a repeated header row. */
    @Test
    fun paginatedTableStreamsIdenticalBytes() {
        fun spec() = pdfDocument(PageConfig(margin = 36.dp, pageNumbers = true)) {
            table(columns = listOf(PdfColumn(2f, "Code"), PdfColumn(1f, "N", TextAlign.End))) {
                repeat(200) { row("ROW-${it.toString().padStart(4, '0')}", "$it") }
            }
        }
        val expected = spec().render(regular(), bold())
        assertContentEquals(expected, stream(spec()))
    }

    /**
     * The same spec instance rendered twice must produce the same bytes — otherwise the parity tests
     * (which build a fresh spec per transport) would be hiding hidden per-render state.
     */
    @Test
    fun specIsReusableAcrossRendersAndTransports() {
        val spec = kitchenSink()
        val first = spec.render(regular(), bold())
        val second = spec.render(regular(), bold())
        assertContentEquals(first, second, "render() must be pure w.r.t. the spec")

        val streamedA = stream(spec)
        val streamedB = stream(spec)
        assertContentEquals(first, streamedA, "renderTo on a reused spec must match render")
        assertContentEquals(streamedA, streamedB, "renderTo must be pure w.r.t. the spec")

        val third = spec.render(regular(), bold())
        assertContentEquals(first, third, "render after renderTo must still match")
    }

    /** Sink chunking must not be observable: writing through a 1-byte-at-a-time sink gives same bytes. */
    @Test
    fun sinkSeesOffsetAndLengthCorrectly() {
        val spec = kitchenSink()
        val expected = spec.render(regular(), bold())
        val out = ByteArrayOutputStream()
        spec.renderTo({ bytes, off, len ->
            // Copy byte-by-byte through the offset/length contract rather than trusting bulk write.
            for (i in 0 until len) out.write(bytes[off + i].toInt())
        }, regular(), bold())
        assertContentEquals(expected, out.toByteArray())
    }

    /** Per-page progress must be emitted identically by both transports. */
    @Test
    fun progressSequenceMatchesRender() {
        val fromRender = ArrayList<Float>()
        kitchenSink().render(regular(), bold(), onProgress = { fromRender.add(it) })
        val fromStream = ArrayList<Float>()
        kitchenSink().renderTo({ _, _, _ -> }, regular(), bold(), onProgress = { fromStream.add(it) })
        assertContentEquals(fromRender, fromStream, "onProgress sequence must be identical")
        assertTrue(fromRender.first() == 0f && fromRender.last() == 1f, "must start at 0f and end at 1f")
        assertTrue(fromRender.dropLast(1).drop(1).all { it <= 0.99f }, "per-page progress must stay <= 0.99")
    }
}
