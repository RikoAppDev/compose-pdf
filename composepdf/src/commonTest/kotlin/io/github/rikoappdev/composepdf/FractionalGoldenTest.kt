/**
 * Cross-platform identity gate for **fractional** lengths: fractional margins, gaps, paddings,
 * borders, radii, divider thickness and font sizes, a Medium run and a page-aware footer, laid out
 * with the deterministic [StubMetrics]. The millipoint engine must reproduce this golden exactly on
 * JVM, Android and iOS, like [GoldenLayoutTest] does for whole-point documents.
 */
class FractionalGoldenTest {

    @Test
    fun fractionalLayoutIsIdenticalToGolden() {
        assertEquals(FRACTIONAL_GOLDEN, fractionalCanonical())
    }
}

